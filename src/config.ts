import type {
  N0ctBadge,
  N0ctConfig,
  N0ctNativeSidebarItem,
  N0ctNormalizedConfig,
  N0ctNormalizedSidebarItem,
  N0ctSidebarTopic,
} from './types.js';

const titleCase = (value: string) => value
  .replace(/[-_]+/g, ' ')
  .replace(/\b\w/g, (character) => character.toUpperCase());

const stripSlashes = (value: string) => value.trim().replace(/^\/+|\/+$/g, '').replace(/\/{2,}/g, '/');

function assertSafePath(value: string, context: string) {
  const normalized = stripSlashes(value);
  if (
    !normalized ||
    normalized.split('/').some((segment) => segment === '.' || segment === '..') ||
    /[\\:?#\s\u0000-\u001f]/.test(normalized)
  ) {
    throw new Error(`N0ctane ${context} must be a non-empty path without dot segments, backslashes, spaces, query strings, or fragments.`);
  }
  return normalized;
}

function normalizeSafeHref(raw: string, context: string) {
  const value = raw.trim();
  if (!value || /[\u0000-\u001f]/.test(value)) {
    throw new Error(`N0ctane ${context} must be a non-empty URL without control characters.`);
  }
  const scheme = /^([a-z][a-z\d+.-]*):/i.exec(value)?.[1]?.toLowerCase();
  if (scheme && !['http', 'https', 'mailto', 'tel'].includes(scheme)) {
    throw new Error(`N0ctane ${context} cannot use the ${scheme}: URL scheme.`);
  }
  return value;
}

function normalizeTopicLink(link: string) {
  const value = normalizeSafeHref(link, 'sidebar topic link');
  return value.startsWith('/') || /^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(value) ? value : `/${value}`;
}

function inferDirectory(link?: string, fallback?: string) {
  if (fallback) return assertSafePath(fallback, 'sidebar directory');
  if (!link || /^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(link)) return undefined;
  const pathname = link.split(/[?#]/, 1)[0] ?? '';
  const directory = stripSlashes(pathname);
  return directory ? assertSafePath(directory, 'sidebar link directory') : undefined;
}

function normalizeBadge(badge: N0ctBadge) {
  return typeof badge === 'string' ? { text: badge } : badge;
}

export function topicToSidebar(topic: N0ctSidebarTopic): N0ctNormalizedSidebarItem {
  if (typeof topic === 'string') {
    const directory = assertSafePath(topic, 'sidebar topic');
    return {
      label: titleCase(directory.split('/').at(-1) ?? directory),
      items: [{ autogenerate: { directory } }],
    };
  }

  const topicLabel = topic.label.trim();
  if (!topicLabel) throw new Error('N0ctane sidebar topic labels must not be empty.');
  const directory = inferDirectory(topic.link, topic.directory);
  if (topic.directory) assertSafePath(topic.directory, 'sidebar directory');
  const shouldGenerate = topic.autogenerate === true
    || (topic.autogenerate !== null && typeof topic.autogenerate === 'object')
    || (topic.autogenerate === undefined && topic.items === undefined && Boolean(directory));
  const autoDirectory = typeof topic.autogenerate === 'object'
    ? (topic.autogenerate.directory
      ? assertSafePath(topic.autogenerate.directory, 'autogenerate directory')
      : directory)
    : directory;
  if (shouldGenerate && !autoDirectory) {
    throw new Error(`N0ctane sidebar topic \"${topic.label}\" enables autogeneration but has no directory. Set \"directory\" or provide an internal \"link\" from which one can be inferred.`);
  }
  const label = topic.icon && !/^\[[^\]]+\]/.test(topic.label)
    ? `[${topic.icon}] ${topicLabel}`
    : topicLabel;

  // A non-autogenerated topic with only a link is a standalone sidebar link.
  // Starlight uses `slug` for docs pages and `link` for external/non-doc URLs.
  if (!shouldGenerate && topic.items === undefined && topic.link) {
    const link = normalizeTopicLink(topic.link);
    const base = {
      label,
      ...(topic.badge ? { badge: normalizeBadge(topic.badge) } : {}),
      ...(topic.attrs ? { attrs: topic.attrs } : {}),
      ...(topic.translations ? { translations: topic.translations } : {}),
    };
    if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(link)) {
      return { ...base, link };
    }
    return { ...base, slug: stripSlashes(link.split(/[?#]/, 1)[0] ?? '') };
  }

  const items: N0ctNativeSidebarItem[] = [
    ...(topic.items ?? []),
    ...(shouldGenerate && autoDirectory ? [{ autogenerate: { directory: autoDirectory } } as const] : []),
  ];

  if (topic.items === undefined && !shouldGenerate && !topic.link) {
    throw new Error(`N0ctane sidebar topic \"${topic.label}\" needs a link, directory, manual items, or autogeneration.`);
  }

  return {
    label,
    ...(topic.collapsed !== undefined ? { collapsed: topic.collapsed } : {}),
    ...(topic.badge ? { badge: normalizeBadge(topic.badge) } : {}),
    items,
  };
}

export function normalizeN0ctConfig(input: N0ctConfig): N0ctNormalizedConfig {
  if (!input.title?.trim()) throw new Error('N0ctane config requires a non-empty title.');
  const hasSidebar = input.sidebar?.topics !== undefined || input.sidebar?.extra !== undefined;
  const sidebarTopicDisplay = input.sidebar?.topicDisplay ?? 'collapsible';
  if (!['collapsible', 'list', 'dropdown'].includes(sidebarTopicDisplay)) {
    throw new Error('N0ctane sidebar.topicDisplay must be "collapsible", "list", or "dropdown".');
  }

  for (const item of input.footer?.links ?? []) {
    if (!item.label.trim()) throw new Error('N0ctane footer link labels must not be empty.');
    normalizeSafeHref(item.link, `footer link "${item.label}"`);
  }
  for (const item of input.footer?.icons ?? []) {
    if (!item.icon.trim()) throw new Error('N0ctane footer icon names must not be empty.');
    normalizeSafeHref(item.link, `footer icon link "${item.icon}"`);
  }

  const sidebar: N0ctNormalizedSidebarItem[] | undefined = hasSidebar
    ? [
        ...(input.sidebar?.topics ?? []).map(topicToSidebar),
        ...(input.sidebar?.extra ?? []),
      ]
    : undefined;


  return {
    title: input.title.trim(),
    ...(input.description ? { description: input.description } : {}),
    ...(sidebar ? { sidebar } : {}),
    sidebarTopicDisplay,
  };
}
